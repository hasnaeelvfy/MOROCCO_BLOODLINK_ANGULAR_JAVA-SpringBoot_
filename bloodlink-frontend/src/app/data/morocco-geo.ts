export const CITIES = REGIONS.flatMap((region) => [...CITIES_BY_REGION[region]]);

export const CITY_REGION: Record<string, Region> = Object.fromEntries(
  REGIONS.flatMap((region) => CITIES_BY_REGION[region].map((city) => [city, region]))
) as Record<string, Region>;

export function citiesForRegion(region: string): string[] {
  return [...(CITIES_BY_REGION[region as Region] ?? [])];
}

export function regionOfCity(city: string): Region {
  return CITY_REGION[city] ?? 'Casablanca-Settat';
}

export function cityIdOf(city: string): number {
  const index = CITIES.indexOf(city);
  return index >= 0 ? index + 1 : 1;
}

export function cityNameOf(id: number | null | undefined): string {
  if (id == null || id < 1) return '—';
  return CITIES[id - 1] ?? '—';
}

