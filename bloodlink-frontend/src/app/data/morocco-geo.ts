export function localizedCityName(name: string | null | undefined, locale: string): string {
  if (!name) return '—';
  const aliases: Record<string, string> = {
    Tanger: 'Tangier',
    Tétouan: 'Tetouan',
    Tetouan: 'Tetouan',
    Fès: 'Fes',
    Fez: 'Fes',
    Salé: 'Sale',
    'El Hoceima': 'Al Hoceima',
    'Al-Hoceima': 'Al Hoceima',
    'Dar Bouazza': 'Dar Bouazza',
    'Casablanca': 'Casablanca'
  };
  const canonical = CITY_AR[name] ? name : aliases[name] ?? name;
  if (locale === 'ar-MA') return CITY_AR[canonical] ?? CITY_AR[name] ?? name;
  if (locale === 'fr') return CITY_FR[canonical] ?? CITY_FR[name] ?? name;
  return canonical;
}
